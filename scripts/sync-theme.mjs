import { readFile, mkdir, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const palette = await readFile(new URL('src/theme-palette.css', root), 'utf8');
const layout = (await readFile(new URL('src/app.css', root), 'utf8'))
  .replaceAll('.apple-notes-ui', ':root:not(.apple-notes-layout-disabled)');
const generated = palette + '\n/* notes layout: generated by scripts/sync-theme.mjs. */\n' + layout;
const target = new URL('themes/apple-notes.css', root);

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (current !== generated) {
    console.error('bundled theme is stale. run npm run theme:sync.');
    process.exitCode = 1;
  } else {
    console.log('bundled theme is up to date.');
  }
} else {
  await mkdir(new URL('themes/', root), { recursive: true });
  await writeFile(target, generated);
  console.log('updated themes/apple-notes.css');
}
