"""Generate the bundled first-paint theme without changing the user's settings."""

import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the theme is stale.')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    palette = (root / 'theme-palette.css').read_text(encoding='utf-8')
    layout = (root / 'app.css').read_text(encoding='utf-8').replace(
        '.apple-notes-ui', ':root:not(.apple-notes-layout-disabled)'
    )
    generated = palette + '\n/* Notes layout: generated by scripts/sync-theme.py. */\n' + layout
    target = root / 'themes/apple-notes.css'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != generated:
            parser.exit(1, 'Bundled theme is stale. Run npm run theme:sync.\n')
        print('Bundled theme is up to date.')
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generated, encoding='utf-8')
    print(target)


if __name__ == '__main__':
    main()
